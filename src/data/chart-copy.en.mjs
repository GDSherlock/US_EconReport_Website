export function chartText(value,locale='zh') {
 if(locale!=='en'||!value)return value;
 if(chartCopyEn[value])return chartCopyEn[value];
 if(/[\u3400-\u9fff]/u.test(value))throw new Error(`Missing English chart copy: ${value}`);
 return value;
}
export function localizeChart(resolved,locale='zh') {
 if(locale==='zh')return resolved;
 return {...resolved,definition:{...resolved.definition,title:chartText(resolved.definition.title,locale),note:chartText(resolved.definition.note,locale)},panels:resolved.panels.map(p=>({...p,title:chartText(p.title,locale),...(p.tenors?{tenors:p.tenors.map(t=>({...t,label:t.months<12?`${t.months}M`:`${t.months/12}Y`}))}:{}),series:p.series.map(s=>({...s,name:chartText(s.name,locale)}))})),metadata:resolved.metadata.map(s=>({...s,name:chartText(s.name,locale),measure:chartText(s.measure,locale)}))};
}
